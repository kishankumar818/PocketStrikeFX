export function validateMcpPort(portInput: string | number): {
  valid: boolean;
  port: number;
  error?: string;
} {
  const parsed = typeof portInput === 'number' ? portInput : Number(String(portInput).trim());
  if (!Number.isInteger(parsed)) {
    return { valid: false, port: 7331, error: 'Port must be a whole integer.' };
  }
  if (parsed < 1024 || parsed > 65535) {
    return {
      valid: false,
      port: 7331,
      error: 'Port must be between 1024 and 65535.',
    };
  }
  return { valid: true, port: parsed };
}

export function sanitizeProjectFolderName(apkOrAppName: string): string {
  const cleaned = apkOrAppName
    .trim()
    .replace(/\.apk$/i, '')
    .trim()
    .replace(/[^a-zA-Z0-9_-]+/g, '_')
    .replace(/^_+|_+$/g, '');
  const base = cleaned.length > 0 ? cleaned : 'MyApp';
  return base.endsWith('_Copy') ? base : `${base}_Copy`;
}

